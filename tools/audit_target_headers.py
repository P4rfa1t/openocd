#!/usr/bin/env python3
"""AUDIT (read-only): for each third-party target file in src/target/, check
whether the project-internal headers it includes actually exist.

WHY
---
A third-party target .c can be a byte-perfect copy and still be unbuildable,
because it was written against a header layout this tree no longer has --
either a header that was renamed/merged upstream, or one that never existed in
upstream at all (a fork-private header sitting next to the .c in its own repo).

`config.h` is filtered out: it is generated by autoconf at build time and is
supposed to be absent from the source tree.

This answers "what would I have to port" for a group of files, without
attempting a build.
"""

from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = HERE / "src"

# The third-party target files (basename, no extension) known to live in
# src/target/ as flat files rather than inside an upstream-arch subdirectory.
THIRD = """
aarch64_coproc_reg adi_v5_cmsis_dap arc32 arc_core arc_dbg arc_mntr arc_ocd
arc_regs arc_trgt c28x cortex_a8 cortex_m3 hexagon loongarch loongarch_ejtag
loongarch_pracc mchp_ri4_bridge mchp_ri4_native nds32 nds32_aice nds32_cmd
nds32_disassembler nds32_reg nds32_tlb nds32_v2 nds32_v3 nds32_v3_common
nds32_v3m nds_vtarget nds_vtarget_cmd ndsv5_ace ndsv5_burner_server ndsv5_cmd
ndsv5_profiling or1k_jtag or1k_jtag_adv tms320 vexriscv vortex86 quark_d2000
quark_se wch_riscv-013 wch_riscv
""".split()

GENERATED = {"config.h"}


def main() -> int:
    if not SRC.is_dir():
        print("ERROR: src/ not found", file=sys.stderr)
        return 1

    have = {p.name for p in SRC.rglob("*.h")}
    missing: dict[str, list[str]] = {}

    for name in THIRD:
        p = SRC / "target" / f"{name}.c"
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        for inc in re.findall(r'#include\s+"([^"]+)"', text):
            if pathlib.Path(inc).name in GENERATED:
                continue
            if pathlib.Path(inc).name not in have:
                missing.setdefault(name, []).append(inc)

    print(f"checked {len(THIRD)} third-party target files against {len(have)} headers")
    if not missing:
        print("MISSING HEADERS: none")
        return 0

    print(f"\nMISSING HEADERS: {sum(len(v) for v in missing.values())} across {len(missing)} files")
    for name in sorted(missing):
        uniq = sorted(set(missing[name]))
        print(f"  src/target/{name}.c")
        for u in uniq:
            print(f"      needs {u}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
