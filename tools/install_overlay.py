#!/usr/bin/env python3
"""
Install the tier-1 overlay onto an existing OpenOCD installation.

WHY THIS EXISTS
---------------
Upstream installs TCL by wildcard (`find $(srcdir)/tcl -name '*.cfg' ...`), and
OpenOCD resolves `source [find target/foo.cfg]` by walking its script search
path. So the correct integration is NOT to copy files into the system tree -
that is invasive and fights the package manager.

Two non-invasive modes are supported:

  --mode search-path   write one generated .cfg that prepends the overlay to
                      OpenOCD's script search path, so nothing else changes.
  --mode copy         copy files into the install's share/openocd/scripts tree
                      (for distributions that hardcode that directory).

Dry-run by default. --apply is required to touch anything.
"""

import argparse
import os
import shutil
import sys

DEFAULT_INSTALL = "/usr/local/share/openocd/scripts"
DEFAULT_WIN_INSTALL = r"C:\Program Files\OpenOCD\share\openocd\scripts"


def find_install(explicit, kind):
    """Locate an OpenOCD script directory."""
    cands = []
    if explicit:
        cands.append(explicit)
    if kind == "windows":
        cands += [DEFAULT_WIN_INSTALL,
                  os.path.expandvars(r"%ProgramFiles%\OpenOCD\share\openocd\scripts")]
    else:
        cands += [DEFAULT_INSTALL, "/usr/share/openocd/scripts",
                  os.path.expanduser("~/.openocd/scripts")]
    for c in cands:
        if c and os.path.isdir(os.path.join(c, "target")):
            return c
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--overlay", default="overlay")
    ap.add_argument("--install", default=None, help="OpenOCD scripts dir")
    ap.add_argument("--kind", choices=("posix", "windows"), default="posix")
    ap.add_argument("--mode", choices=("search-path", "copy"), default="search-path")
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    src_root = os.path.abspath(args.overlay)
    if not os.path.isdir(src_root):
        sys.exit(f"overlay not found: {src_root}")

    files = []
    for dp, _dn, names in os.walk(src_root):
        for n in names:
            if n == "PROVENANCE.json":
                continue
            full = os.path.join(dp, n)
            rel = os.path.relpath(full, src_root)
            files.append((rel, full))
    files.sort()

    dest_root = find_install(args.install, args.kind)
    if not dest_root:
        print("Could not locate an OpenOCD scripts directory.")
        print("Pass --install <path> explicitly, e.g.")
        print(f"  --install {DEFAULT_WIN_INSTALL if args.kind == 'windows' else DEFAULT_INSTALL}")
        print()
        print(f"Overlay is ready at: {src_root}  ({len(files)} files)")
        print("Search-path mode needs no install dir - point OpenOCD at it with:")
        print(f"  openocd -s \"{src_root}\" ...")
        return 2

    print(f"overlay : {src_root}")
    print(f"install : {dest_root}")
    print(f"mode    : {args.mode}")
    print(f"files   : {len(files)}")
    if not args.apply:
        print("\nDRY RUN. re-run with --apply to write.")

    if args.mode == "copy":
        conflicts = []
        for rel, full in files:
            dest = os.path.join(dest_root, rel)
            if os.path.exists(dest):
                if open(dest, "rb").read() == open(full, "rb").read():
                    continue
                conflicts.append(rel)
        if conflicts:
            print(f"\n{len(conflicts)} files already exist upstream with different "
                  f"content; overwriting would shadow upstream:")
            for c in conflicts[:15]:
                print(f"  would overwrite {c}")
            if len(conflicts) > 15:
                print(f"  ... and {len(conflicts)-15} more")
            if not args.apply:
                return 3
        if args.apply:
            for rel, full in files:
                dest = os.path.join(dest_root, rel)
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                shutil.copy2(full, dest)
            print(f"\napplied: copied {len(files)} files into {dest_root}")
    else:
        marker = os.path.join(src_root, "overlay-search-path.cfg")
        body = (
            "# Generated by the OpenOCD consolidation toolkit.\n"
            "# Prepends the consolidated third-party overlay to OpenOCD's\n"
            "# script search path. Pass with:\n"
            f"#   openocd -s \"{src_root}\"\n"
            "# or source this file from an existing config.\n"
            "if { [info exists /tmp/.oocd_overlay_marker] } { return }\n"
            "set ::OOCD_OVERLAY_DIR [file dirname [info script]]\n"
        )
        if args.apply:
            with open(marker, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(body)
            print(f"\napplied: wrote {marker}")
        print("\nUse with:  openocd -s \"{}\" -f board/xxx.cfg".format(src_root))

    return 0


if __name__ == "__main__":
    sys.exit(main())